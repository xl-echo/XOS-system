/* ===========================================================================
 * XOS 内核运行时支持：64 位整数除法 / 取模
 *
 * 为什么需要这个文件
 * ------------------
 * 内核以 -ffreestanding -nostdlib 编译，编译器不会链接任何运行时库。
 * 一旦代码里出现 u64 / u64 或 u64 % u64（含被内联的表达式），GCC 就会
 * 生成对 __udivdi3 / __umoddi3 的调用；这两个符号在 libgcc 里，而本内核
 * 不链接 libgcc，于是链接期直接报 undefined reference。
 *
 * 两种应对方式：
 *   (a) 逐个改写调用点，用移位与 32 位除法绕开 64 位除法；
 *   (b) 在本内核内自带一份 64 位除法实现。
 *
 * 本文件采取 (b)。理由是 64 位除法是内核的通用基础设施：
 * 物理地址、容量统计、时间戳换算、性能计数都会用到，靠"每处都记得绕开"
 * 是不可持续的做法 —— 一旦后续任何一个模块漏掉一处，构建就会失败。
 * 有了这份实现，调用点可以自由使用 64 位算术，可读性也不再被牺牲。
 *
 * 算法
 * ----
 * 移位-减法（restoring division）：从最高位到最低位逐位试商。
 * 每一步把余数左移一位并带入被除数的下一位；若移出的位为 1（说明余数
 * 已超出 64 位容量）或余数已不小于除数，则本位置 1 并减去除数。
 * 全程只使用移位、按位或、比较与减法，不产生任何除法指令，
 * 因此不会递归依赖自身。
 *
 * 复杂度：固定 64 次循环，O(1) 时间、O(1) 空间，无分支预测依赖的
 * 长链，适合在中断上下文与早期启动阶段调用。
 * =========================================================================== */

#include "types.h"

/* ---------------------------------------------------------------------------
 * 64 位无符号除法与取模（一次算完商和余数）
 *
 * 入参：
 *   n    被除数
 *   d    除数；d == 0 时商返回 0、余数返回 n（不陷入异常，见下）
 *   rem  余数的输出位置；传 0 表示不需要余数
 * 返回：
 *   商 n / d
 *
 * 除零处理：硬件除零会触发 #DE 异常。本函数是编译器隐式调用的运行时例程，
 * 调用点并没有做除零判断，因此这里不主动陷入 —— 返回商 0、余数等于被除数，
 * 让调用方得到一个确定且可解释的结果。需要严格语义的调用点必须自行先判零。
 * ------------------------------------------------------------------------- */
u64 __udivmoddi4(u64 n, u64 d, u64 *rem)
{
    u64 q = 0;
    u64 r = 0;
    int i;

    if (d == 0) {
        if (rem != 0) *rem = n;
        return 0;
    }

    for (i = 63; i >= 0; i--) {
        /* carry：本轮左移将被挤出 64 位的最高位。
         * 它一旦为 1，说明当前余数（含新带入位）一定大于等于 2^64 > d，
         * 必须置商位并减去除数 —— 否则该位会被静默丢弃，结果出错。 */
        u64 carry = r >> 63;

        r = (r << 1) | ((n >> i) & 1ull);

        if (carry != 0 || r >= d) {
            r -= d;
            q |= (1ull << i);
        }
    }

    if (rem != 0) *rem = r;
    return q;
}

/* 无符号除法：n / d */
u64 __udivdi3(u64 n, u64 d)
{
    return __udivmoddi4(n, d, 0);
}

/* 无符号取模：n % d */
u64 __umoddi3(u64 n, u64 d)
{
    u64 r = 0;
    (void)__udivmoddi4(n, d, &r);
    return r;
}

/* ---------------------------------------------------------------------------
 * 有符号版本
 *
 * GCC 在遇到 i64 / i64 时另有一套符号（__divdi3 / __moddi3）。
 * 当前内核尚未出现有符号 64 位除法，但一并提供可以避免将来某个模块
 * 第一次用到它时又撞上链接失败。
 *
 * 语义按 C99：商向零截断，余数符号跟随被除数。
 * ------------------------------------------------------------------------- */
i64 __divmoddi4(i64 n, i64 d, i64 *rem)
{
    int nneg = (n < 0);
    int dneg = (d < 0);
    u64 un = nneg ? (u64)(-(n + 1)) + 1ull : (u64)n;
    u64 ud = dneg ? (u64)(-(d + 1)) + 1ull : (u64)d;
    u64 ur = 0;
    u64 uq = __udivmoddi4(un, ud, &ur);
    i64 q = (i64)uq;

    if (nneg != dneg) q = -q;
    if (rem != 0) *rem = nneg ? -(i64)ur : (i64)ur;
    return q;
}

i64 __divdi3(i64 n, i64 d)
{
    return __divmoddi4(n, d, 0);
}

i64 __moddi3(i64 n, i64 d)
{
    i64 r = 0;
    (void)__divmoddi4(n, d, &r);
    return r;
}
